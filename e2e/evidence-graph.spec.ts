import { readFile } from 'node:fs/promises';
import { test, expect } from '@playwright/test';
import graphDocuments from '../examples/evidence/graph-documents.json' with { type: 'json' };

test('Graph Search finds a five-hop lexical miss with exact explanations, independent reviews and export; no inference', async ({ page }) => {
  let calls = 0; const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.route(/\/api\/(?:assess|evidence)$/, async (route) => { calls++; await route.abort(); });
  await page.goto('http://127.0.0.1:3198'); await page.getByRole('button', { name: 'Evidence', exact: true }).click();
  const signoff = page.getByRole('article', { name: 'Dispatch queue procedure / Queue procedure / Final gate', exact: true });
  await expect(page.getByLabel('Search strategy')).toHaveValue('text');
  await expect(signoff).toHaveCount(0);
  await expect(page.getByText('Text Search 4; Graph Search 7.', { exact: false })).toBeVisible();
  await page.getByLabel('Search strategy').selectOption('graph');
  await expect(signoff).toBeVisible(); await expect(signoff).toContainText('dispatch-signoff@1:34-107');
  await signoff.getByText('Graph retrieval path · 5 hops · control seed', { exact: true }).click();
  await expect(signoff).toContainText('related_control (forward)');
  await expect(signoff).toContainText('references (forward)');
  await expect(signoff).toContainText('This register calls Human Oversight the Two-person Gate control');
  await expect(signoff).toContainText('dispatch-gates@2 / Dispatch gate register / Related sources');
  await page.getByText('Graph relationships and unresolved references (2)', { exact: true }).click();
  await expect(page.getByText('Pinned document/section reference is unresolved;', { exact: false })).toBeVisible();
  await expect(page.getByText('Pinned target or source is outside', { exact: false })).toBeVisible();
  await signoff.getByText('Review passage: not reviewed', { exact: true }).click();
  await signoff.getByLabel('Evidence judgment').selectOption('ambiguous');
  await signoff.getByLabel('Retrieval relevance').selectOption('relevant');
  await signoff.getByRole('button', { name: 'Save evidence review' }).click();
  await expect(page.getByText('Reviewed relevant pool: text 0/1; graph 1/1.', { exact: false })).toBeVisible();
  await page.getByLabel('Passage to judge').selectOption('retrieval-miss');
  await expect(page.getByRole('button', { name: 'Judge selected passage with Jev' })).toBeDisabled();
  await page.getByLabel('Traversal depth').selectOption('4'); await expect(signoff).toHaveCount(0);
  await page.getByLabel('Traversal depth').selectOption('5'); await expect(signoff).toContainText('Review passage: ambiguous');
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export complete experiment' }).click();
  const exported = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(exported.search.strategy).toBe('graph'); expect(exported.runs).toEqual([]);
  const hit = exported.search.result.hits.find((entry: { passage: { id: string } }) => entry.passage.id === 'dispatch-signoff@1:34-107');
  expect(hit.path.steps).toHaveLength(5); expect(hit.passage.text).toBe('A staff member must countersign each proposal before it leaves the queue.');
  expect(exported.search.graph.configuration.version).toBe('oversight-links-1');
  expect(exported.search.graph.edges.some((edge: { kind: string }) => edge.kind === 'human_review')).toBe(true);
  expect(exported.classificationEvaluation.n).toBe(0);
  await page.locator('.lab-panel').evaluate((element) => { element.scrollTop = 0; });
  await page.screenshot({ path: 'test-results/graph-search-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/graph-search-mobile.png', fullPage: true });
  expect(calls).toBe(0); expect(errors).toEqual([]);
});

test('archive scope preserves conflicting revisions and added control reviews without overwriting history', async ({ page }) => {
  await page.goto('http://127.0.0.1:3198'); await page.getByRole('button', { name: 'Evidence', exact: true }).click();
  await page.getByLabel('Search strategy').selectOption('graph');
  await page.getByLabel('Governance control').selectOption('two-person-gate');
  const oldDocument = graphDocuments.find((entry) => entry.revision === '1')!;
  const oldText = oldDocument.content.split('\n\n').at(-1)!;
  const oldStart = oldDocument.content.indexOf(oldText);
  const oldId = `dispatch-gates@1:${oldStart}-${oldStart + oldText.length}`;
  const oldRule = page.getByRole('article').filter({ has: page.getByText(oldId, { exact: true }) });
  const newRule = page.getByRole('article').filter({ has: page.getByText('dispatch-gates@2:224-348', { exact: true }) });
  await expect(oldRule).toHaveCount(0); await expect(newRule).toBeVisible();
  await page.getByLabel('Include archived revisions', { exact: false }).check();
  await expect(oldRule).toBeVisible(); await expect(newRule).toBeVisible();
  for (const [article, label] of [[oldRule, 'supported'], [newRule, 'contradicted']] as const) {
    await article.getByText('Review passage: not reviewed', { exact: true }).click();
    await article.getByLabel('Evidence judgment').selectOption(label);
    await article.getByLabel('Retrieval relevance').selectOption('relevant');
    await article.getByRole('button', { name: 'Save evidence review' }).click();
  }
  await page.getByLabel('Include archived revisions', { exact: false }).uncheck(); await expect(oldRule).toHaveCount(0);
  const download = page.waitForEvent('download'); await page.getByRole('button', { name: 'Export evidence + reviews' }).click();
  const exported = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(exported.reviews).toHaveLength(2);
  expect(exported.reviews.map((entry: { passage: { revision: string } }) => entry.passage.revision).sort()).toEqual(['1', '2']);
  expect(exported.search.result.query.includeArchived).toBe(false);
  await page.reload(); await page.getByRole('button', { name: 'Evidence', exact: true }).click();
  await page.getByLabel('Governance control').selectOption('two-person-gate');
  await page.getByLabel('Search strategy').selectOption('graph');
  await page.getByLabel('Include archived revisions', { exact: false }).check();
  await expect(oldRule).toContainText('Review passage: supported'); await expect(newRule).toContainText('Review passage: contradicted');
});
