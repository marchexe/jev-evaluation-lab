import { readFile } from 'node:fs/promises';
import { test, expect } from '@playwright/test';
import graphDocuments from '../examples/evidence/graph-documents.json' with { type: 'json' };
import { compareSources, inspectCompared, openDisclosure, openJev, inspectPassage , openReview } from './workflows';

test('side-by-side search exposes a five-hop miss, provenance, bounds and exact offline export', async ({ page }) => {
  let calls = 0; const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.route(/\/api\/(assess|evidence)$/, async route => { calls++; await route.abort(); });
  await page.goto('http://127.0.0.1:3198'); await page.getByRole('button', { name: 'Belege', exact: true }).click();
  await openDisclosure(page, '.search-comparison-details');
  const table = await compareSources(page);
  const queue = 'dispatch-signoff@1:34-107';
  const queueRow = table.locator('tr[data-passage-id="'+queue+'"]');
  await expect(queueRow).toHaveAttribute('data-text-rank', '');
  await expect(queueRow).toHaveAttribute('data-graph-rank', '5');
  const signoff = await inspectCompared(page, queue);
  await expect(signoff).toContainText(queue);
  await openDisclosure(page, '.source-provenance');
  await signoff.getByText('Suchpfad · 5 Schritte · Kontroll-Start', { exact: true }).click();
  for (const quote of ['Verwandte Kontrolle (vorwärts)', 'Quellenverweis (vorwärts)', 'Dieses Register bezeichnet die menschliche Aufsicht beim Dispatch-Assistenten als Vier-Augen-Freigabe.', 'dispatch-gates@2 / Dispatch-Freigaberegister / Zugehörige Quellen']) await expect(signoff).toContainText(quote);
  await openDisclosure(page, '.search-settings');
  await page.getByText('Verknüpfungen und offene Verweise (2)', { exact: true }).click();
  await expect(page.getByText('Der festgelegte Dokument- oder Abschnittsverweis ist nicht auflösbar.', { exact: false })).toBeVisible();
  await expect(page.getByText('Quelle oder Ziel liegt außerhalb', { exact: false })).toBeVisible();
  await openReview(signoff);
  await signoff.getByLabel('Belegaussage').selectOption('ambiguous');
  await signoff.getByLabel('Suchrelevanz').selectOption('relevant');
  await signoff.getByRole('button', { name: 'Bewertung speichern' }).click();
  await page.getByText('Suchvergleich – Details', { exact: true }).click();
  await expect(page.getByText('Bewertete relevante Belege: Text 0/1; graph 1/1.', { exact: false })).toBeVisible();
  await openJev(page); await expect(page.getByRole('button', { name: 'Mit Jev bewerten' })).toBeDisabled();
  await page.getByLabel('Suchtiefe').selectOption('4'); await expect(queueRow).toHaveCount(0);
  await page.getByLabel('Suchtiefe').selectOption('5'); await inspectCompared(page, queue);
  await expect(signoff).toContainText('Bewertung: Mehrdeutig');
  if (await page.locator('.evidence-tools').count()) await openDisclosure(page,'.evidence-tools');
  const downloaded = page.waitForEvent('download'); await page.getByRole('button', { name: 'Experiment exportieren' }).click();
  const exported = JSON.parse(await readFile((await (await downloaded).path())!, 'utf8'));
  expect(exported.search.strategy).toBe('graph'); expect(exported.runs).toEqual([]);
  const hit = exported.search.result.hits.find((entry: { passage: { id: string } }) => entry.passage.id === queue);
  expect(hit.path.steps).toHaveLength(5); expect(hit.passage.text).toBe('A staff member must countersign each proposal before it leaves the queue.');
  expect(exported.search.graph.configuration.version).toBe('oversight-links-1');
  expect(exported.search.graph.edges.some((edge: { kind: string }) => edge.kind === 'human_review')).toBe(true);
  expect(exported.classificationEvaluation.n).toBe(0);
  await page.setViewportSize({ width:1280, height:900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(calls).toBe(0); expect(errors).toEqual([]);
});

test('archive scope retains contradictory revisions and independent review identities', async ({ page }) => {
  await page.goto('http://127.0.0.1:3198'); await page.getByRole('button', { name:'Belege', exact:true }).click();
  await page.getByLabel('Kontrolle').selectOption('two-person-gate');
  await openDisclosure(page, '.search-settings'); await page.getByLabel('Suchverfahren für Bewertung und Export').selectOption('graph');
  const oldDocument = graphDocuments.find(entry => entry.revision === '1')!;
  const oldText = oldDocument.content.split('\n\n').at(-1)!; const start = oldDocument.content.indexOf(oldText);
  const oldId = `dispatch-gates@1:${start}-${start + oldText.length}`, newId = 'dispatch-gates@2:224-348';
  await expect(page.getByLabel('Quellabschnitt', { exact:true }).locator(`option[value="${oldId}"]`)).toHaveCount(0);
  await page.getByLabel('Archivierte Versionen einbeziehen', { exact:false }).check();
  for (const [id, label] of [[oldId,'supported'],[newId,'contradicted']] as const) {
    const article = await inspectPassage(page, id);
    await openReview(article);
    await article.getByLabel('Belegaussage').selectOption(label);
    await article.getByLabel('Suchrelevanz').selectOption('relevant');
    await article.getByRole('button', { name:'Bewertung speichern' }).click();
  }
  await page.getByLabel('Archivierte Versionen einbeziehen', { exact:false }).uncheck();
  await expect(page.getByLabel('Quellabschnitt', { exact:true }).locator(`option[value="${oldId}"]`)).toHaveCount(0);
  if (await page.locator('.evidence-tools').count()) await openDisclosure(page,'.evidence-tools');
  const download = page.waitForEvent('download'); await page.getByRole('button', {name:'Belege und Bewertungen exportieren'}).click();
  const exported = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(exported.reviews).toHaveLength(2); expect(exported.reviews.map((entry: {passage:{revision:string}}) => entry.passage.revision).sort()).toEqual(['1','2']);
  expect(exported.search.result.query.includeArchived).toBe(false);
  await page.reload(); await page.getByRole('button', {name:'Belege',exact:true}).click();
  await page.getByLabel('Kontrolle').selectOption('two-person-gate'); await openDisclosure(page,'.search-settings');
  await page.getByLabel('Suchverfahren für Bewertung und Export').selectOption('graph'); await page.getByLabel('Archivierte Versionen einbeziehen', {exact:false}).check();
  for (const [id,label] of [[oldId,'supported'],[newId,'contradicted']]) await expect(await inspectPassage(page,id)).toContainText(`Bewertung: ${label === 'supported' ? 'Gestützt' : 'Widersprochen'}`);
});
