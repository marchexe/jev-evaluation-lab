test('evidence retrieval, human review, export and Evaluate work offline with inference disabled', async ({ page }) => {
  let calls = 0;
  await page.route('**/api/assess', async (route) => { calls++; await route.abort(); });
  await page.goto('http://127.0.0.1:3198');
  await page.getByRole('button', { name: 'Belege', exact: true }).click();
  await expect(page.locator('.control-statement')).toBeVisible();
  await openDisclosure(page, '.search-comparison-details');
  const policy = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Richtlinie des Dispatch-Assistenten', exact: true }) });
  const runbook = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Betriebshandbuch des Dispatch-Assistenten', exact: true }) });
  await expect(policy).toContainText('muss jede Empfehlung genehmigen');
  await expect(page.getByRole('region', { name: 'Gefundene Quellen' })).toContainText('ohne menschliche Freigabe');
  await page.screenshot({ path: 'test-results/evidence-desktop.png', fullPage: true });
  await openReview(policy);
  await policy.getByLabel('Belegaussage').selectOption('supported');
  await policy.getByLabel('Suchrelevanz').selectOption('relevant');
  await policy.getByLabel('Kommentar').fill('Approval gate documented.');
  await policy.getByRole('button', { name: 'Bewertung speichern' }).click();
  await expect(policy).toContainText('Bewertung: Gestützt');
  await page.getByLabel('System').selectOption('ledger');
  await expect(page.getByRole('region', { name: 'Gefundene Quellen' }).getByText('Keine Treffer.', { exact: false })).toBeVisible();
  await openDisclosure(page, '.source-browser-details');
  await page.getByLabel('Alle Quellabschnitte anzeigen', { exact: false }).check();
  await expect(page.getByRole('article')).toHaveCount(1);
  await evaluateEvidence(page);
  await expect(page.getByRole('region', { name: 'Evidence evaluation' })).toContainText('gefunden 1 / 1');
  if (await page.locator('.evidence-tools').count()) await openDisclosure(page,'.evidence-tools');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Belege und Bewertungen exportieren' }).click();
  const data = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(data.reviews[0].passage.text).toContain('must approve every recommendation');
  expect(data.reviews[0].passage.documentId).toBe('dispatch-policy');
  await page.reload(); await page.getByRole('button', { name: 'Belege', exact: true }).click();
  await openReview(policy);
  await policy.getByLabel('Belegaussage').selectOption('uncertain');
  await policy.getByRole('button', { name: 'Bewertung speichern' }).click();
  await expect(policy).toContainText('Bewertung: Unsicher');
  await policy.getByRole('button', { name: 'Bewertung löschen' }).click();
  await expect(policy).toContainText('Bewertung: nicht bewertet');
  await page.setViewportSize({ width: 1280, height: 900 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/evidence-desktop-compact.png', fullPage: true });
  expect(calls).toBe(0);
});

test('invalid evidence storage is preserved and can be exported without overwriting it', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('jev.evidence-reviews.v1', '{broken'));
  await page.goto('http://127.0.0.1:3198');
  await page.getByRole('button', { name: 'Belege', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Belegsuche' }).getByRole('alert')).toContainText('nicht lesbar');
  await openDisclosure(page,'.evidence-tools');
  await expect(page.getByRole('button', { name: 'Belege und Bewertungen exportieren' })).toBeDisabled();
  await openJev(page);
  await expect(page.getByRole('button', { name: 'Experiment exportieren' })).toBeDisabled();
  await expect(page.getByRole('table', { name: 'Evidence confusion matrix' })).toHaveCount(0);
  await expect(page.getByRole('status').filter({ hasText: 'Bewertungen nicht verfügbar.' })).toBeVisible();
  if (await page.locator('.evidence-tools').count()) await openDisclosure(page,'.evidence-tools');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Gespeicherte Belege exportieren' }).click();
  expect(await readFile((await (await download).path())!, 'utf8')).toBe('{broken');
  expect(await page.evaluate(() => localStorage.getItem('jev.evidence-reviews.v1'))).toBe('{broken');
});

test('all six human references can be recorded and exported before any model predictions exist', async ({ page }) => {
  let calls = 0;
  await page.route(/\/api\/(?:assess|evidence)$/, async (route) => { calls++; await route.abort(); });
  await page.goto('http://127.0.0.1:3198');
  await page.getByRole('button', { name: 'Belege', exact: true }).click();
  await openDisclosure(page, '.source-browser-details');
  await page.getByLabel('Alle Quellabschnitte anzeigen', { exact: false }).check();
  const labels = ['supported', 'contradicted', 'ambiguous', 'insufficient_evidence', 'insufficient_evidence', 'ambiguous'];
  for (const [index, entry] of manifest.cases.entries()) {
    const document = documents.find((value) => value.id === entry.documentId)!;
    await page.getByLabel('System').selectOption(document.systemId);
    const marker = `## ${entry.section.split(' / ').at(-1)}\n\n`;
    const start = document.content.indexOf(marker) + marker.length;
    const text = document.content.slice(start).split('\n\n')[0];
    const passage = await inspectPassage(page, `${document.id}@${document.revision}:${start}-${start + text.length}`, true);
    await openReview(passage);
    await passage.getByLabel('Belegaussage').selectOption(labels[index]);
    await passage.getByLabel('Suchrelevanz').selectOption([3, 4].includes(index) ? 'not_relevant' : 'relevant');
    await passage.getByLabel('Kommentar').fill('Pre-inference reviewer annotation example.');
    await passage.getByRole('button', { name: 'Bewertung speichern' }).click();
  }
  await openJev(page);
  const panel = page.getByRole('region', { name: 'Jev-Belegbewertung', exact: true });
  await expect(panel).toContainText('0 gespeicherte Läufe');
  await expect(panel).toContainText('Feste Referenzfälle: 6; davon ohne Vorhersage: 6');
  await openDisclosure(page, '.review-progress');
  await expect(page.getByRole('region', { name: 'Belegsuche' })).toContainText('gefunden 3 / 4 manuell relevante Abschnitte; übersehen 1');
  await page.reload(); await evaluateEvidence(page);
  if (await page.locator('.evidence-tools').count()) await openDisclosure(page,'.evidence-tools');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Experiment exportieren' }).click();
  const exported = JSON.parse(await readFile((await (await download).path())!, 'utf8'));
  expect(exported.humanReviewsAtExport).toHaveLength(6);
  for (const [index, entry] of manifest.cases.entries()) {
    const review = exported.humanReviewsAtExport.find((value: { passage: { documentId: string; section: string } }) => value.passage.documentId === entry.documentId && value.passage.section === entry.section);
    expect(review.judgment).toBe(labels[index]); expect(review.controlId).toBe(entry.controlId);
    expect(review.passage.revision).toBe(entry.revision);
    expect(documents.find((document) => document.id === entry.documentId)!.content.slice(review.passage.start, review.passage.end)).toBe(review.passage.text);
  }
  expect(exported.runs).toEqual([]);
  expect(exported.classificationEvaluation.n).toBe(0);
  expect(exported.classificationEvaluation.missingPredictions).toBe(6);
  expect(calls).toBe(0);
});
