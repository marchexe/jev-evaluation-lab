import { readFile } from 'node:fs/promises';
import { test, expect } from '@playwright/test';
import { openReview, openDisclosure } from './workflows';

test('English evidence workflow reruns locally, keeps review independent, and exports the exact source', async ({ page }) => {
  let calls=0; const errors: string[]=[];
  page.on('pageerror', error=>errors.push(error.message));
  await page.route('**/api/**', async route=>{calls++;await route.abort();});
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto('http://127.0.0.1:3198');
  await page.getByLabel('Sprache wählen',{exact:true}).selectOption('en');
  await page.getByRole('button',{name:'Evidence',exact:true}).click();
  await page.getByRole('button',{name:'Find sources',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('No Jev request');
  await expect(page.locator('.search-comparison')).toBeHidden();
  await expect(page.locator('.source-browser')).toBeHidden();
  await expect(page.getByRole('region',{name:'Retrieved sources'}).getByRole('button')).toHaveCount(7);
  await page.screenshot({path:'results/evidence-workflow/english-dark.png',fullPage:false});
  const inspector=page.locator('#passage-inspector');
  await expect(inspector.getByLabel('Evidence judgment')).toBeHidden();
  await expect(page.locator('.machine-review > summary')).toHaveText('Jev review');
  await openReview(inspector);
  await inspector.getByLabel('Evidence judgment').selectOption('supported');
  await inspector.getByLabel('Retrieval relevance').selectOption('relevant');
  await inspector.getByRole('button',{name:'Save review',exact:true}).click();
  await expect(page.locator('.evidence-steps')).toHaveCount(0);
  await expect(page.getByRole('status')).toContainText('saved');
  await openDisclosure(page,'.evidence-tools');
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Export evidence and reviews',exact:true}).click();
  const exported=JSON.parse(await readFile((await (await download).path())!,'utf8'));
  expect(exported.reviews[0].passage.id).toBe('dispatch-policy@1:47-186');
  expect(exported.reviews[0].passage.text).toContain('A human supervisor must approve every recommendation');
  expect(exported.search.strategy).toBe('graph');
  await page.reload(); await page.getByRole('button',{name:'Evidence',exact:true}).click();
  await openReview(inspector);
  await expect(inspector.getByLabel('Evidence judgment')).toHaveValue('supported');
  await openDisclosure(page,'.search-comparison-details');
  await page.getByLabel('Differences only',{exact:true}).uncheck();
  await expect(page.locator('tr[data-text-rank]:not([data-text-rank=""])')).toHaveCount(4);
  await expect(page.locator('tr[data-graph-rank]:not([data-graph-rank=""])')).toHaveCount(7);
  expect(calls).toBe(0);expect(errors).toEqual([]);
});
