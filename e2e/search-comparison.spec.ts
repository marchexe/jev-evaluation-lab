import { test, expect } from '@playwright/test';
import { openDisclosure } from './workflows';

for (const language of ['de','en'] as const) test('aligned comparison explains a graph-only source inline in '+language, async ({page})=>{
  let calls=0;const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/api/**',async route=>{calls++;await route.abort();});
  await page.emulateMedia({colorScheme:'dark'});
  await page.goto('http://127.0.0.1:3198');
  if(language==='en')await page.getByLabel('Sprache wählen',{exact:true}).selectOption('en');
  await page.getByRole('button',{name:language==='en'?'Evidence':'Belege',exact:true}).click();
  await openDisclosure(page,'.search-comparison-details');
  const comparison=page.locator('.search-comparison');
  const table=page.locator('.comparison-source-table');
  const filter=page.getByLabel(language==='en'?'Differences only':'Nur Unterschiede',{exact:true});
  await expect(filter).toBeChecked();await expect(table.locator('tr[data-passage-id]')).toHaveCount(3);
  const queue=table.locator('tr[data-passage-id="dispatch-signoff@1:34-107"]');
  await expect(queue).toHaveAttribute('data-text-rank','');await expect(queue).toHaveAttribute('data-graph-rank','5');
  await expect(queue).toContainText(language==='en'?'Not returned':'Nicht ausgegeben');
  await queue.getByRole('button').scrollIntoViewIfNeeded();const scroll=await page.evaluate(()=>scrollY);
  await queue.getByRole('button').click();
  expect(await page.evaluate(()=>scrollY)).toBe(scroll);
  const detail=page.getByRole('region',{name:language==='en'?'Selected comparison source':'Ausgewählte Vergleichsquelle'});
  await expect(detail).toContainText(language==='en'?'A staff member must countersign':'muss jeden Vorschlag gegenzeichnen');
  await expect(detail.locator('.comparison-path li')).toHaveCount(6);
  await expect(detail).toContainText(language==='en'?'documented relationships':'dokumentierte Verknüpfungen');
  await detail.locator('.comparison-technical > summary').click();
  await detail.locator('.type-reference > summary').click();
  await expect(detail).toContainText('dispatch-signoff@1:34-107');
  await expect(detail).toContainText('dispatch-gates@2');
  await filter.uncheck();await expect(table.locator('tr[data-passage-id]')).toHaveCount(7);
  await filter.check();await expect(table.locator('tr[data-passage-id]')).toHaveCount(3);
  await page.setViewportSize({width:1280,height:900});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  expect(await comparison.evaluate(element=>[...element.querySelectorAll('*')].every(child=>!['auto','scroll'].includes(getComputedStyle(child).overflowY)||child.scrollHeight<=child.clientHeight))).toBe(true);
  await detail.locator('.comparison-technical > summary').click();
  await comparison.scrollIntoViewIfNeeded();
  await page.screenshot({path:'results/search-comparison/comparison-'+language+'.png',fullPage:false});
  await detail.getByRole('button',{name:language==='en'?'Review this passage':'Diesen Abschnitt bewerten',exact:true}).click();
  await expect(page.locator('#passage-inspector')).toBeFocused();
  await expect(page.locator('#passage-inspector')).toContainText(language==='en'?'A staff member must countersign':'muss jeden Vorschlag gegenzeichnen');
  expect(calls).toBe(0);expect(errors).toEqual([]);
});
